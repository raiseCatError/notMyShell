/** Deterministic production-renderer captures. Simulated owner events; never launches a shell. */
import {mkdirSync, writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {join} from 'node:path';
import {QueueDispatcher} from '../../src/session/QueueDispatcher.js';
import {CommandQueue, type QueueState} from '../../src/session/CommandQueue.js';
import {queueBlock} from '../../src/status/queueStatus.js';
import {queueActivitySummary} from '../../src/status/executionTimeline.js';
import {planScreen, regionOf, withQueueRows} from '../../src/app/screenPlan.js';
import {AnsiOutputParser} from '../../src/output/AnsiOutputParser.js';
import {stripAnsi, truncateAnsi} from '../../src/util/text.js';

const directory = process.argv[2] ?? 'docs/development/execution-timeline-slice-1';
mkdirSync(directory, {recursive: true});
const sha = execFileSync('git', ['rev-parse','HEAD'], {encoding:'utf8'}).trim();
const dirty = execFileSync('git', ['status','--porcelain'], {encoding:'utf8'}).trim().length > 0;
function fixture(kind: string): {state: QueueState; now: number} {
  let now = 1_000_000;
  const clock = {now: () => now, monotonic: () => now};
  const owner = new QueueDispatcher({isReady:true, adapter:{id:'zsh'}, submit() {}}, new CommandQueue(() => now), clock);
  owner.onExec('npm run build');
  for (const text of ['npm test','git status','echo done','pwd']) owner.request({op:'add', text});
  now += 8200; owner.onPrompt(0); owner.onExec('npm test'); now += 3100;
  if (kind === 'success') { owner.onPrompt(0); owner.onExec('git status'); now += 200; }
  if (kind === 'failure') owner.onPrompt(17);
  if (kind === 'manual pause') { owner.request({op:'pause'}); owner.onPrompt(0); }
  if (kind === 'interruption') { owner.onInterrupt(); owner.onPrompt(130); }
  if (kind === 'completed') { owner.onPrompt(0); for (const command of ['git status','echo done','pwd']) { owner.onExec(command); now+=200; owner.onPrompt(0); } }
  return {state: owner.state, now};
}
const escapeXml = (text: string) => text.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const cases = ['running','success','failure','manual pause','interruption','completed'];
const markdown = [`# Slice 1 production-renderer previews`, '', `Source HEAD: ${sha}${dirty ? ' (working tree contains uncommitted changes)' : ''}.`, '',
  'Generated by `rtk env -u NO_COLOR TERM=xterm-256color COLORTERM=truecolor node --import=tsx scripts/dev/execution-timeline-preview.ts`.', '',
  'These are actual queueBlock/renderExecutionTimeline and queueActivitySummary outputs from deterministic session-owner event fixtures, not hand-authored mockups or physical terminal QA. Each capture uses production screenPlan/withQueueRows to bound the timeline; PTY dimensions are asserted unchanged. The gallery freezes one normal activity-animation frame. Safe/NO_COLOR captures settle the same renderer without color.', ''];
const svg = [`<svg xmlns="http://www.w3.org/2000/svg" width="1040" height="1360" viewBox="0 0 1040 1360"><rect width="1040" height="1360" fill="#17171d"/><g font-family="Menlo,DejaVu Sans Mono,monospace" font-size="12">`];
for (const [caseIndex, kind] of cases.entries()) {
  const {state, now} = fixture(kind);
  markdown.push(`## ${kind}`, '');
  for (const [variant,columns,rows] of [['normal',80,30],['narrow',32,18]] as const) {
    const base = planScreen({rows,inputRows:1,suggestions:0,running:true,detached:false,hasOutput:true,contextPlacement:'header',hasVisibleContext:true,composerLayout:'twoLine',transcriptRows:400});
    const budget = Math.min(rows >= 30 ? 7 : 3, Math.max(0,base.transcript.height-3));
    const content = queueBlock(state,columns,budget,{now,animate:true,animationElapsed:330}) ?? [];
    const plan = withQueueRows(base,content.length,true);
    if (plan.ptyRows !== base.ptyRows || (regionOf(plan,'queue')?.height ?? 0) !== content.length) throw new Error('preview geometry diverged');
    const capture = [...content,truncateAnsi(queueActivitySummary(state),columns)];
    markdown.push(`### ${variant}: ${columns} columns × ${rows} rows`, '', '```text', ...capture.map(stripAnsi), '```', '');
    writeFileSync(join(directory,`${kind.replaceAll(' ','-')}-${columns}.ansi`),capture.join('\r\n')+'\r\n');
    const originX = variant === 'normal' ? 20 : 700;
    const originY = 30 + caseIndex*220;
    svg.push(`<text x="${originX}" y="${originY}" fill="#b0b8c2">${escapeXml(kind)} · ${columns} columns</text>`);
    capture.forEach((row,index) => {
      const parser = new AnsiOutputParser(); parser.write(row);
      let column = 0;
      for (const cell of parser.allLines()[0] ?? []) {
        if (!cell) continue;
        const rgb = [...cell.style.matchAll(/\u001b\[38;2;(\d+);(\d+);(\d+)m/gu)].at(-1);
        const fill = rgb ? `rgb(${rgb[1]},${rgb[2]},${rgb[3]})` : '#f2f0ec';
        svg.push(`<text x="${originX+column*8}" y="${originY+24+index*20}" fill="${fill}">${escapeXml(cell.text)}</text>`);
        column += cell.width;
      }
    });
  }
}
const savedNoColor = process.env.NO_COLOR, savedIcons = process.env.NMSH_ICONS;
process.env.NO_COLOR = '1'; process.env.NMSH_ICONS = 'safe';
markdown.push('## Safe / NO_COLOR at 32 columns','');
for (const kind of cases) {
  const {state,now} = fixture(kind);
  markdown.push(`### ${kind}`, '', '```text', ...(queueBlock(state,32,4,{now,animate:false}) ?? []).map(stripAnsi), '```', '');
}
if (savedNoColor === undefined) delete process.env.NO_COLOR; else process.env.NO_COLOR=savedNoColor;
if (savedIcons === undefined) delete process.env.NMSH_ICONS; else process.env.NMSH_ICONS=savedIcons;
svg.push('</g></svg>');
writeFileSync(join(directory,'previews.md'),markdown.join('\n'));
writeFileSync(join(directory,'previews.svg'),svg.join('\n'));
process.stdout.write(`Production previews written to ${directory}\n`);
