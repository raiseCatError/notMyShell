/** Deterministic Queue settings captures: the real RowPanel and the production timeline preview. Never launches a shell. */
import {mkdirSync, writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {join} from 'node:path';
import {DEFAULT_PROMPT_CONFIGURATION, type PromptConfiguration} from '../../src/prompt/configuration.js';
import {createRowPanel, renderRowPanel} from '../../src/ui/RowPanel.js';
import {QUEUE_SETTINGS_ROW_IDS} from '../../src/ui/SettingsPanel.js';
import {queueSettingsPreview} from '../../src/status/queueSettingsPreview.js';
import {setIconStyle} from '../../src/ui/glyphs.js';
import {stripAnsi} from '../../src/util/text.js';

const directory = process.argv[2] ?? 'docs/development/execution-timeline-slice-2';
mkdirSync(directory, {recursive: true});
const sha = execFileSync('git', ['rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();
const dirty = execFileSync('git', ['status', '--porcelain', '--untracked-files=no'], {encoding: 'utf8'}).trim().length > 0;
const withQueue = (patch: Partial<PromptConfiguration['queue']>): PromptConfiguration =>
  ({...DEFAULT_PROMPT_CONFIGURATION, queue: {...DEFAULT_PROMPT_CONFIGURATION.queue, ...patch}});
const render = (config: PromptConfiguration, columns: number, rows: number): string[] =>
  renderRowPanel(createRowPanel('Queue', '/queue · /settings queue', [...QUEUE_SETTINGS_ROW_IDS], 'queue'), config, columns, rows,
    queueSettingsPreview(config, Math.max(24, columns - 4)));

const markdown = [`# Slice 2A Queue settings previews`, '', `Source HEAD: ${sha}${dirty ? ' (working tree contains uncommitted changes)' : ''}.`, '',
  'Generated by `env -u NO_COLOR TERM=xterm-256color COLORTERM=truecolor node --import=tsx scripts/dev/queue-settings-preview.ts`.', '',
  'Actual renderRowPanel output with queueSettingsPreview: the production timeline renderer over frozen observed facts, drawn with the current palette and glyph mode. No shell is started and nothing is executed. `default` is also saved as ANSI next to this file.', ''];
const capture = (name: string, config: PromptConfiguration, columns: number, rows: number): void => {
  const lines = render(config, columns, rows);
  markdown.push(`## ${name} · ${columns} × ${rows}`, '', '```text', ...lines.map(stripAnsi), '```', '');
  if (name === 'default') writeFileSync(join(directory, 'queue-settings-default.ansi'), lines.join('\r\n') + '\r\n');
};

capture('default', withQueue({}), 80, 30);
capture('timeline off', withQueue({liveTimeline: false}), 80, 30);
capture('compact terminal', withQueue({}), 80, 24);
capture('one result, one upcoming, 30s retention', withQueue({recentResults: 1, upcoming: 1, transientSeconds: 30}), 80, 30);
setIconStyle('safe');
capture('safe glyphs', withQueue({}), 80, 30);
setIconStyle('nerd');
writeFileSync(join(directory, 'queue-settings-preview.md'), markdown.join('\n'));
console.log(`wrote ${join(directory, 'queue-settings-preview.md')}`);
