/**
 * Deterministic Slice 2C previews:
 * 1. Queue settings with queueOutputDisplay ('inline' vs 'fold')
 * 2. Multiline paste execution choices (block, queue, edit, cancel)
 * 3. Refusal handling with clear explanation and disabled queue choice
 * 4. Bounded narrow terminal captures (32x18, 50x20, 80x24)
 *
 * Never launches a real shell process or executes commands.
 */
import {mkdirSync, writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {join} from 'node:path';
import {DEFAULT_PROMPT_CONFIGURATION, type PromptConfiguration} from '../../src/prompt/configuration.js';
import {createRowPanel, renderRowPanel} from '../../src/ui/RowPanel.js';
import {QUEUE_SETTINGS_ROW_IDS} from '../../src/ui/SettingsPanel.js';
import {queueSettingsPreview} from '../../src/status/queueSettingsPreview.js';
import {createBatchReview, createBatchReviewWithRefusal, renderBatchReview, batchReviewKey} from '../../src/input/BatchReview.js';
import {setIconStyle} from '../../src/ui/glyphs.js';
import {stripAnsi} from '../../src/util/text.js';

const directory = process.argv[2] ?? 'docs/development/execution-timeline-slice-2c';
mkdirSync(directory, {recursive: true});

const sha = execFileSync('git', ['rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();
const dirty = execFileSync('git', ['status', '--porcelain', '--untracked-files=no'], {encoding: 'utf8'}).trim().length > 0;

const withQueue = (patch: Partial<PromptConfiguration['queue']>): PromptConfiguration =>
  ({...DEFAULT_PROMPT_CONFIGURATION, queue: {...DEFAULT_PROMPT_CONFIGURATION.queue, ...patch}});

const markdown: string[] = [
  '# Slice 2C Production Previews: Output Folding & Multiline Paste Choices',
  '',
  `Source HEAD: ${sha}${dirty ? ' (working tree contains uncommitted changes)' : ''}.`,
  '',
  'Deterministic production-renderer captures over frozen observed facts.',
  'Generated by `node --import=tsx scripts/dev/queue-slice-2c-preview.ts`.',
  '',
  '## 1. Queue Settings: Output Display (Inline vs Fold)',
  '',
];

// Capture 1: Settings Panel with outputDisplay = 'inline' (default)
const inlineConfig = withQueue({outputDisplay: 'inline'});
const inlinePanel = renderRowPanel(
  createRowPanel('Queue', '/queue · /settings queue', [...QUEUE_SETTINGS_ROW_IDS], 'queue'),
  inlineConfig,
  80,
  30,
  queueSettingsPreview(inlineConfig, 76)
);
markdown.push('### Queue Settings · Inline output display (default)', '', '```text', ...inlinePanel.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'queue-settings-inline.ansi'), inlinePanel.join('\n') + '\n');

// Capture 2: Settings Panel with outputDisplay = 'fold'
const foldConfig = withQueue({outputDisplay: 'fold'});
const foldPanel = renderRowPanel(
  createRowPanel('Queue', '/queue · /settings queue', [...QUEUE_SETTINGS_ROW_IDS], 'queue'),
  foldConfig,
  80,
  30,
  queueSettingsPreview(foldConfig, 76)
);
markdown.push('### Queue Settings · Fold queued output enabled', '', '```text', ...foldPanel.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'queue-settings-fold.ansi'), foldPanel.join('\n') + '\n');

markdown.push('## 2. Multiline Paste: 4-Way Execution Choices', '');

const samplePaste = 'git fetch origin\ngit pull --ff-only\nnpm test';

// Capture 3: Multiline Paste Review - Default choice (Queue separately)
const reviewQueue = createBatchReview(samplePaste, 'bash', 20)!;
const queueReviewLines = renderBatchReview(reviewQueue, 80, 24);
markdown.push('### Multiline Paste Review · Default Choice: 2 Queue separately', '', '```text', ...queueReviewLines.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'paste-review-choice-queue.ansi'), queueReviewLines.join('\n') + '\n');

// Capture 4: Multiline Paste Review - Focused Choice (1 Run as block)
const reviewBlock = createBatchReview(samplePaste, 'bash', 20)!;
batchReviewKey(reviewBlock, {kind: 'text', value: '1'}, 24);
const blockReviewLines = renderBatchReview(reviewBlock, 80, 24);
markdown.push('### Multiline Paste Review · Focused Choice: 1 Run as block', '', '```text', ...blockReviewLines.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'paste-review-choice-block.ansi'), blockReviewLines.join('\n') + '\n');

// Capture 5: Multiline Paste Review - Focused Choice (3 Edit)
const reviewEdit = createBatchReview(samplePaste, 'bash', 20)!;
batchReviewKey(reviewEdit, {kind: 'text', value: '3'}, 24);
const editReviewLines = renderBatchReview(reviewEdit, 80, 24);
markdown.push('### Multiline Paste Review · Focused Choice: 3 Edit in composer', '', '```text', ...editReviewLines.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'paste-review-choice-edit.ansi'), editReviewLines.join('\n') + '\n');

// Capture 6: Multiline Paste Review - Separation Refusal
const refusedPaste = 'cat <<EOF\nline1\nline2'; // unclosed heredoc
const reviewRefused = createBatchReviewWithRefusal(refusedPaste, 'bash', 20, 'Unclosed heredoc construct');
const refusedReviewLines = renderBatchReview(reviewRefused, 80, 24);
markdown.push('### Multiline Paste Review · Separation Refusal (Queue Disabled)', '', '```text', ...refusedReviewLines.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'paste-review-refusal.ansi'), refusedReviewLines.join('\n') + '\n');

// Capture 7: Narrow layout (50x20)
const narrowReviewLines = renderBatchReview(reviewQueue, 50, 20);
markdown.push('### Narrow Layout · 50 × 20 Terminal', '', '```text', ...narrowReviewLines.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'paste-review-narrow-50.ansi'), narrowReviewLines.join('\n') + '\n');

// Capture 8: Safe glyphs mode
setIconStyle('safe');
const safeReviewLines = renderBatchReview(reviewQueue, 80, 24);
markdown.push('### Safe Glyphs Mode · 80 × 24 Terminal', '', '```text', ...safeReviewLines.map(stripAnsi), '```', '');
writeFileSync(join(directory, 'paste-review-safe-glyphs.ansi'), safeReviewLines.join('\n') + '\n');
setIconStyle('nerd');

writeFileSync(join(directory, 'README.md'), markdown.join('\n'));
console.log(`Generated Slice 2C previews in ${directory}`);
